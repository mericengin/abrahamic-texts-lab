#!/usr/bin/env python3
"""Write docs/data-inventory.md: what is downloaded, which PDF and Markdown versions exist, and what the checks found.

Reads only the provenance and conversion records (data/raw/*/MANIFEST.json, data/processed/**/CONVERSION.json, PDFS.json,
OCR.json), never the texts themselves, so the report is safe to commit. Usage: python3 scripts/data_report.py
"""
from __future__ import annotations

import json
import tomllib
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RAW, PROC = ROOT / "data" / "raw", ROOT / "data" / "processed"


def load(p: Path):
    return json.loads(p.read_text()) if p.exists() else None


def mb(n: int) -> str:
    return f"{n / 1e6:.1f} MB"


def main() -> int:
    with (ROOT / "data" / "sources.toml").open("rb") as fh:
        sources = {s["id"]: s for s in tomllib.load(fh)["source"]}
    out = ["# Data inventory", "",
           "Generated by `scripts/data_report.py` from the provenance records. It lists what exists locally, never the texts themselves "
           "(third-party texts are git-ignored and stay on the owner's machine). Regenerate it after any download or conversion.", "",
           f"Generated: {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}", ""]
    for sid in sorted(d.name for d in RAW.iterdir() if d.is_dir()):
        m = load(RAW / sid / "MANIFEST.json")
        if not m:
            continue
        s = sources.get(sid, {})
        out += [f"## {sid}", "", f"- **What:** {s.get('name', '')} ({s.get('language', '')})",
                f"- **License:** {m.get('license')} ([terms]({m.get('license_url')}))",
                f"- **Credit line:** {m.get('attribution')}", f"- **Status when fetched:** {m.get('status_at_fetch')}; retrieved {m['retrieved_utc']}"]
        if m.get("commit"):
            out.append(f"- **Raw:** git checkout at commit `{m['commit'][:12]}`" + (f", paths {m['paths']}" if m.get("paths") not in (None, "all") else ""))
        for f in m.get("files", []):
            out.append(f"- **Raw file:** `{f['file']}`, {f['bytes']:,} bytes, sha256 `{f['sha256'][:16]}…`")
        pdfs = load(PROC / "pdf" / sid / "PDFS.json")
        for key, p in (pdfs or {}).get("pdfs", {}).items():
            out.append(f"- **Generated PDF:** `{p['pdf']}`, {p['pages']} pages, {mb(p['bytes'])}, {p['verses']:,} verses (reading copy built from the data, not an official edition)")
        conv = load(PROC / "markdown" / sid / "CONVERSION.json")
        if conv:
            for key, v in conv.get("versions", {}).items():
                rt = v["markdown_roundtrip"]
                exp = f", expected {v['expected_verses']:,}" if v.get("expected_verses") else ""
                st = v["stats"]
                n = st.get("verses", st.get("ayas"))
                out.append(f"- **Markdown `{key}/`:** {v['files']} files, {n:,} verses{exp}, empty verses {v['empty_verses']}, read-back check {'passed' if rt['ok'] else 'FAILED'}")
            for fname, f in conv["files"].items():
                q = f.get("ocr_quality")
                qs = f", OCR quality {q['flag']}" + (f" ({q['score']} common words per 1000)" if q and q.get("score") else "") if q else ""
                extra = f", {f['pages']} pages" if f.get("pages") else ""
                lossless = ", lossless" if f.get("lossless") else ""
                out.append(f"- **Markdown of `{fname}`:** `{f['markdown']}`{extra}{lossless}{qs}")
            if conv.get("pickthall_only"):
                p = conv["pickthall_only"]
                out.append(f"- **Pickthall-only extraction:** {p['verses_found']:,} verses in {p['suras_found']} suras (standard count {p['reference_total_verses_standard_count']:,}); "
                           f"{len(p['repaired_corrupted_verse_ids'])} corrupted verse ids repaired and logged")
        layers = load(PROC / "markdown" / sid / "OCR_LAYERS.json")
        if layers:
            for name in ("raw", "normalized"):
                l = layers[name]
                out.append(f"- **Markdown of the fresh OCR ({name}):** `{l['file']}`, {l['bytes']:,} bytes, {l['common_words_per_1000']} common German words per 1000, "
                           f"{l['tokens_seen_3_or_more_times_percent']}% of tokens seen 3 or more times")
            out.append(f"- **Normalization:** {layers['corrections']:,} logged repairs {layers['by_rule']}; near-empty pages {layers['near_empty_pages']} (blank or show-through pages)")
        ocr = load(PROC / "ocr" / sid / "OCR.json")
        if ocr:
            out.append(f"- **Fresh OCR:** {ocr['pages']} pages with {ocr['tesseract']}, model `{ocr['language_model']}`, {ocr['dpi']} dpi, psm {ocr['psm']}; near-empty pages: {len(ocr['empty_pages'])}")
        out.append("")
    (ROOT / "docs" / "data-inventory.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote docs/data-inventory.md ({len(out)} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
